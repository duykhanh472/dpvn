/// Xây dựng zip trong bộ nhớ từ danh sách `(tên_tệp, nội_dung)`.
fn build_zip(entries: &[(&str, &[u8])]) -> Vec<u8> {
    let mut buf = Vec::new();
    {
        let mut zip = zip::ZipWriter::new(std::io::Cursor::new(&mut buf));
        let options = zip::write::SimpleFileOptions::default()
            .compression_method(zip::CompressionMethod::Stored);
        for (name, data) in entries {
            zip.start_file(*name, options).expect("start_file");
            zip.write_all(data).expect("write_all");
        }
        zip.finish().expect("zip finish");
    }
    buf
}

// ───────────────────────────────────────────────────────────────────────────────
// Test: nhập bình thường 2 trang hợp lệ
// ───────────────────────────────────────────────────────────────────────────────

#[tokio::test]
async fn test_ingest_dry_run_two_valid_pages() {
    let zip = build_zip(&[
        ("0001.png", VALID_PNG_200X300),
        ("0001.txt", "Trang một nội dung".as_bytes()),
        ("0002.png", VALID_PNG_200X300),
        ("0002.txt", "Trang hai nội dung".as_bytes()),
    ]);

    let preview = dry_run(&zip).await.expect("dry_run phải thành công");

    assert_eq!(preview.total_pages, 2, "phải có 2 trang");
    assert_eq!(preview.error_count, 0, "không có lỗi");
    assert!(preview.can_commit(), "phải có thể commit");
}

// ───────────────────────────────────────────────────────────────────────────────
// Test: ảnh hỏng bị từ chối với tên tệp trong thông báo lỗi
// ───────────────────────────────────────────────────────────────────────────────

#[tokio::test]
async fn test_ingest_corrupt_image_rejected_with_filename() {
    // Phải dùng tên số để pairing nhận ra (Format A: NNNN.png)
    let corrupt = b"this is definitely not a valid PNG or JPEG";
    let zip = build_zip(&[
        ("0001.png", corrupt.as_ref()),
        ("0001.txt", "nội dung".as_bytes()),
    ]);

    let preview = dry_run(&zip).await.expect("dry_run phải trả về preview");

    // Ảnh hỏng → lỗi được thu thập vào errors, không phải hard IngestError
    assert!(
        preview.error_count > 0,
        "phải báo lỗi khi ảnh hỏng, errors = {:?}",
        preview.errors
    );

    let joined = preview.errors.join(" ");
    // Thông báo lỗi phải chứa tên entry ('0001.png' hoặc 'trang 1')
    assert!(
        joined.contains("0001") || joined.contains("trang 1"),
        "thông báo lỗi phải chứa tên tệp hoặc số trang: '{joined}'"
    );
}

// ───────────────────────────────────────────────────────────────────────────────
// Test: khoảng trống số trang tạo ra cảnh báo
// ───────────────────────────────────────────────────────────────────────────────

#[tokio::test]
async fn test_ingest_page_number_gap_produces_warning() {
    // Trang 1 và 3, bỏ qua trang 2 → cảnh báo khoảng trống
    let zip = build_zip(&[
        ("0001.png", VALID_PNG_200X300),
        ("0001.txt", "trang 1".as_bytes()),
        ("0003.png", VALID_PNG_200X300),
        ("0003.txt", "trang 3".as_bytes()),
    ]);

    let preview = dry_run(&zip).await.expect("dry_run phải thành công");

    assert_eq!(preview.total_pages, 2, "phải có 2 trang");

    // Cảnh báo khoảng trống phải xuất hiện ở global_warnings hoặc per-page warnings
    let has_warning = !preview.global_warnings.is_empty()
        || preview.warning_pages > 0
        || preview.pages.iter().any(|p| !p.warnings.is_empty());

    assert!(
        has_warning,
        "phải có cảnh báo khoảng trống trang 1→3; global_warnings={:?}",
        preview.global_warnings
    );
}

// ───────────────────────────────────────────────────────────────────────────────
// Test: path traversal bị từ chối
// ───────────────────────────────────────────────────────────────────────────────

#[tokio::test]
async fn test_ingest_path_traversal_rejected() {
    let zip = build_zip(&[
        ("../etc/passwd.png", VALID_PNG_200X300),
        ("../etc/passwd.txt", b"root:x:0:0"),
    ]);

    let result = dry_run(&zip).await;

    match result {
        Err(IngestError::PathTraversal(_)) => {
            // Đúng: bị từ chối khi kiểm tra zip entries
        }
        Err(other) => {
            // Chấp nhận lỗi khác liên quan đến path bất thường
            let msg = other.to_string();
            let is_related = msg.contains("..")
                || msg.contains("traversal")
                || msg.contains("zip")
                || msg.contains("không an toàn");
            assert!(is_related, "lỗi phải liên quan đến path traversal: {msg}");
        }
        Ok(preview) => {
            // Nếu zip crate normalize tên, entry không thể pair thành trang hợp lệ
            assert!(
                preview.total_pages == 0 || preview.error_count > 0,
                "path traversal không được tạo ra trang hợp lệ (total={}, errors={})",
                preview.total_pages,
                preview.error_count
            );
        }
    }
}

// ───────────────────────────────────────────────────────────────────────────────
// Test: zip trống không có trang
// ───────────────────────────────────────────────────────────────────────────────

#[tokio::test]
async fn test_ingest_empty_zip_no_pages() {
    let zip = build_zip(&[]);

    // Zip trống → NoPagesFound (không có entry nào để pair)
    let result = dry_run(&zip).await;

    match result {
        Err(IngestError::NoPagesFound) => {
            // Đúng: không có trang nào trong zip trống
        }
        Err(other) => panic!("Lỗi không mong đợi từ zip trống: {other}"),
        Ok(preview) => {
            // Một số triển khai trả về preview rỗng thay vì lỗi — chấp nhận
            assert_eq!(preview.total_pages, 0, "zip trống không có trang nào");
        }
    }
}

// ───────────────────────────────────────────────────────────────────────────────
// Test: một trang hợp lệ — các trường preview chính xác
// ───────────────────────────────────────────────────────────────────────────────

#[tokio::test]
async fn test_ingest_preview_fields_accurate() {
    let zip = build_zip(&[
        ("0001.png", VALID_PNG_200X300),
        ("0001.txt", "Dòng 1\nDòng 2\nDòng 3".as_bytes()),
    ]);

    let preview = dry_run(&zip).await.expect("dry_run phải thành công");

    assert_eq!(preview.total_pages, 1);
    assert_eq!(preview.error_count, 0);
    assert!(preview.can_commit());
    assert!(!preview.has_warnings());

    let page = &preview.pages[0];
    assert_eq!(page.page_number, 1);
    assert_eq!(page.width, 200);
    assert_eq!(page.height, 300);
    assert_eq!(page.first_lines.len(), 3);
    assert_eq!(page.first_lines[0], "Dòng 1");
}
